"""Turn data/enrichment/*.csv into the enrichment tables and macros.

The enrichment section makes claims that are easy to get wrong by hand -- how
many terms a query returned, how many of them rest on a single gene, which gene
is carrying a block of terms. All of them are computed here and written as
LaTeX, so the prose cannot drift from the g:Profiler output the notebook saved.

Writes:
    generated/enrichment_values.tex      macros used in the prose
    generated/enrichment_summary.tex     body rows of the per-set summary table
    generated/enrichment_top.tex         body rows of the strongest terms table
"""
import os
from collections import Counter
from pathlib import Path

import pandas as pd

if "PAPER_DATA" in os.environ:
    DATA = Path(os.environ["PAPER_DATA"])
    GEN = Path(os.environ.get("PAPER_GEN", DATA / "generated"))
else:
    ROOT = Path(__file__).resolve().parent.parent
    DATA = ROOT / "data"
    GEN = ROOT / "generated"
GEN.mkdir(parents=True, exist_ok=True)

SETS = [("plsda_up", "PLS-DA, up", "PlsdaUp", "PLSDA_upregulated_genes.csv"),
        ("plsda_down", "PLS-DA, down", "PlsdaDown", "PLSDA_downregulated_genes.csv"),
        ("cvae_up", "CVAE, up", "CvaeUp", "CVAE_upregulated_genes.csv"),
        ("cvae_down", "CVAE, down", "CvaeDown", "CVAE_downregulated_genes.csv")]

# How many of the strongest multi-gene terms to tabulate per set.
TOP_PER_SET = 5


def tex(s):
    """Escape the characters LaTeX reserves. Term names come from a database."""
    s = str(s).replace("\\", r"\textbackslash{}")
    for ch in "&%$#_{}":
        s = s.replace(ch, "\\" + ch)
    s = s.replace("\u2265", r"$\geq$").replace("\u2264", r"$\leq$")
    return s.replace("~", r"\textasciitilde{}").replace("^", r"\textasciicircum{}")


def genes(names):
    """Gene symbols set in italic, the paper's convention for a gene name."""
    return ", ".join(rf"\gene{{{tex(g)}}}" for g in names)


def q(v):
    """An adjusted p-value as *math-mode content without delimiters*, so the
    caller decides whether it lands inside an existing $...$ or needs its own."""
    if v >= 1e-3:
        return f"{v:.3f}"
    e = int(f"{v:.0e}".split("e")[1])
    m = v / 10 ** e
    return rf"{m:.1f}\times 10^{{{e}}}"


def main():
    macros = ["% Generated by scripts/make_enrichment.py -- do not edit by hand.",
              "% Source: data/enrichment/*.csv", ""]
    summary, top = [], []

    for name, label, mac, gene_file in SETS:
        d = pd.read_csv(DATA / "enrichment" / f"{name}.csv")
        nq = len(pd.read_csv(DATA / gene_file))
        if not len(d):
            summary.append(rf"{label} & {nq} & 0 & 0 & 0 & --- \\")
            continue

        # g:Profiler returns one row per database identifier, so a complex that
        # carries several ids appears several times under one name.
        u = (d.sort_values("adjusted_p_value")
               .drop_duplicates(subset=["source", "term_name"]))
        single = u[u.intersection_size == 1]
        multi = u[u.intersection_size >= 2].sort_values("adjusted_p_value")

        drivers = Counter(g for gs in single.intersections.fillna("")
                          for g in str(gs).split(",") if g)
        top_driver = drivers.most_common(1)[0] if drivers else ("---", 0)

        macros += [
            rf"\newcommand{{\vEnr{mac}NQuery}}{{{nq}}}",
            rf"\newcommand{{\vEnr{mac}NUnique}}{{{len(u)}}}",
            rf"\newcommand{{\vEnr{mac}NSingle}}{{{len(single)}}}",
            rf"\newcommand{{\vEnr{mac}NMulti}}{{{len(multi)}}}",
            rf"\newcommand{{\vEnr{mac}TopDriver}}{{\gene{{{tex(top_driver[0])}}}}}",
            rf"\newcommand{{\vEnr{mac}TopDriverN}}{{{top_driver[1]}}}",
            rf"\newcommand{{\vEnr{mac}Sources}}{{{tex(', '.join(dict.fromkeys(u.source)))}}}",
        ]
        if len(multi):
            b = multi.iloc[0]
            macros += [
                rf"\newcommand{{\vEnr{mac}BestTerm}}{{{tex(b.term_name)}}}",
                rf"\newcommand{{\vEnr{mac}BestK}}{{{int(b.intersection_size)}}}",
                rf"\newcommand{{\vEnr{mac}BestSize}}{{{int(b.term_size)}}}",
                rf"\newcommand{{\vEnr{mac}BestQ}}{{{q(b.adjusted_p_value)}}}",
            ]

        summary.append(rf"{label} & {nq} & {len(u)} & {len(multi)} & {len(single)} & "
                       rf"\gene{{{tex(top_driver[0])}}} ({top_driver[1]}) \\")

        # A group header is written as an ordinary row rather than with
        # \multicolumn: a \multicolumn (or a rule) as the first token after an
        # \input resumes inside a tabular breaks TeX's alignment lookahead.
        top.append(rf"\emph{{{label} in AD}} & & & & \\")
        if not len(multi):
            top.append(r"\quad --- & no term reached two query genes & & & \\")
        for _, r in multi.head(TOP_PER_SET).iterrows():
            top.append(rf"\quad {tex(r.source)} & {tex(r.term_name)} & "
                       rf"{int(r.intersection_size)}/{int(r.term_size)} & "
                       rf"${q(r.adjusted_p_value)}$ & "
                       rf"{genes(str(r.intersections).split(','))} \\")
        top.append(r"\addlinespace")

    # The closing rule belongs to the fragment, not to the tabular that reads
    # it (a rule command immediately after \input resumes is a "Misplaced
    # \noalign"); the opening \midrule stays in AD_transcriptome_two_views.tex, where it is adjacent
    # to a real row.
    summary.append(r"\bottomrule")
    top[-1] = r"\bottomrule"

    (GEN / "enrichment_values.tex").write_text("\n".join(macros) + "\n")
    (GEN / "enrichment_summary.tex").write_text("\n".join(summary) + "\n")
    (GEN / "enrichment_top.tex").write_text("\n".join(top) + "\n")
    print(f"wrote {GEN/'enrichment_values.tex'}, "
          f"{GEN/'enrichment_summary.tex'}, {GEN/'enrichment_top.tex'}")


if __name__ == "__main__":
    main()
